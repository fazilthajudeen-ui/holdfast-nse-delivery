def fig_cagr(plt):
    bts = [b for b in P6["backtests"] if "cagr" in b] + [{"variant": "Nifty 500", **P6["benchmark_nifty500_test"], "n_trades": None}]
    fig, ax = plt.subplots(figsize=(3.4, 2.3))
    names = [b["variant"].replace("_", " ") for b in bts]
    vals = [100 * b["cagr"] for b in bts]
    cols = ["0.55" if b["variant"] != "Nifty 500" else "#4C72B0" for b in bts]
    y = np.arange(len(bts))[::-1]
    ax.barh(y, vals, color=cols, height=0.6)
    for yi, b, v in zip(y, bts, vals):
        ax.text(v + (1 if v >= 0 else -1), yi, f"{v:+.1f}%" + (f" ({b['n_trades']} tr.)" if b.get("n_trades") is not None else ""),
                va="center", ha="left" if v >= 0 else "right", fontsize=6)
    ax.axvline(0, color="0.2", lw=0.6)
    ax.set_yticks(y)
    ax.set_yticklabels(names, fontsize=6)
    ax.set_xlabel("CAGR after costs, test 2023–26 (%)")
    ax.set_xlim(min(vals) - 32, max(vals) + 22)
    ax.set_title("Costed backtests  [PRE-REGISTERED]")
    fig.savefig(FIGDIR / "fig_cagr.pdf", bbox_inches="tight")


