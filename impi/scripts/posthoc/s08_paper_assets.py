def esc(s) -> str:
    return str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def mn(s: str) -> str:
    """Typeset a leading minus as a real minus sign (text and math mode)."""
    return "\\ensuremath{-}" + s[1:] if s.startswith("-") else s


def pp(x, d=1, sign=True):
    return "--" if x is None or (isinstance(x, float) and not np.isfinite(x)) else mn(f"{100 * x:+.{d}f}" if sign else f"{100 * x:.{d}f}")


def num(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    return mn(f"{x:.{d}f}")


def pval(p):
    if p is None or (isinstance(p, float) and not np.isfinite(p)):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def table(name, caption, label, cols, header, rows, note=None, wide=False):
    env = "table*" if wide else "table"
    lines = [f"% generated by scripts/posthoc/s08_paper_assets.py from result JSON - do not edit by hand",
             f"\\begin{{{env}}}[t]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\footnotesize",
             "\\setlength{\\tabcolsep}{4pt}", f"\\begin{{tabular}}{{{cols}}}", "\\toprule", header + r" \\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MID" else " & ".join(r) + r" \\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append(f"\\par\\smallskip\\parbox{{{'0.95' if wide else '0.98'}\\linewidth}}{{\\scriptsize\\raggedright {note}}}")
    lines.append(f"\\end{{{env}}}")
    (TABDIR / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return name


